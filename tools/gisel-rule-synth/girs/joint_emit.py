"""TableGen and C++ of the joint region rules (girs/joint.py).

Each rule becomes one GICombineRule whose root is its anchor (an
instruction that the rule replaces), and a C++ description of the rule
for the matcher and the applier of GISelEGraphSynth/GISynthJoint.h:

  td/GISynthJointCombines.td                   the records and the group
  include/GISelEGraphSynth/GISynthJointRules.inc  the descriptions and the
                                               match_<id> / apply_<id>

The emission is a pure function of the rule records: `joint-emit --check`
finds stale generated files.
"""

from . import ops

HEADER = ('Generated by tools/gisel-rule-synth/gi-rule-synth.py joint-emit. '
          'DO NOT EDIT.')

_PRED = {p: 'CmpInst::ICMP_' + p.upper() for p in ops.PREDS}


class EmitError(ValueError):
    pass


def why_not_emittable(rule):
    """The reason why the rule cannot be emitted, or None."""
    from . import joint
    src = rule['source']
    plan = rule['plan']
    if not rule.get('proofs'):
        return 'no proof'
    bad = joint.check_rule(rule)
    if bad:
        return 'inconsistent: ' + '; '.join(bad)
    if len(src['instrs']) > 12 or len(src['inputs']) > 8:
        return 'too many instructions or inputs for GISynthJoint.h'
    cls = _classes(rule)
    if len(cls) > 4:
        return 'too many width classes'
    for ins in src['instrs'] + [
            {'op': n['op'], 'args': n['args'], 'ws': n['ws']}
            for n in plan['new_instruction_dag']]:
        if len(ins['args']) > 3 or len(ins['ws']) > 2:
            return 'an instruction with too many operands or results'
    srcw = {i['w'] for i in src['inputs']}
    for ins in src['instrs']:
        srcw |= set(ins['ws'])
    if set(cls) - srcw:
        return 'a width that no value of the source has'
    return None


def _classes(rule):
    first = rule['plan']['guards']['width_maps'][0]
    return [w for w, _ in first]


def _width(rule, ref):
    src = rule['source']
    if ref[0] == 'in':
        return src['inputs'][ref[1]]['w']
    if ref[0] == 'n':
        return src['instrs'][ref[1]]['ws'][ref[2]]
    if ref[0] == 't':
        return rule['plan']['new_instruction_dag'][ref[1]]['ws'][ref[2]]
    return ref[2]


def _ref(ref, rule=None):
    """The C++ Ref of a value. An input that is a constant is a literal of
    the rule; the other inputs are numbered without the constants."""
    if ref is None:
        return 'Ref()'
    if ref[0] == 'in':
        if rule is not None:
            x = rule['source']['inputs'][ref[1]]
            if 'const' in x:
                c = int(x['const'], 16)
                if c == (1 << x['w']) - 1 and x['w'] > 1:
                    return 'lit(-1)'
                if c >= 1 << 63:
                    return 'lit(int64_t(%dULL))' % c
                return 'lit(%d)' % c
            return 'in(%d)' % _input_index(rule)[ref[1]]
        return 'in(%d)' % ref[1]
    if ref[0] == 'n':
        return 'src(%d, %d)' % (ref[1], ref[2])
    if ref[0] == 't':
        return 'tgt(%d, %d)' % (ref[1], ref[2])
    if ref[0] == 'lit':
        return 'lit(%d)' % {'0': 0, '1': 1, '-1': -1}[ref[1]]
    raise EmitError('no value %r' % (ref,))


def _input_index(rule):
    """Input of the source -> input of the C++ rule (constants are
    literals)."""
    out, n = {}, 0
    for i, x in enumerate(rule['source']['inputs']):
        if 'const' not in x:
            out[i] = n
            n += 1
    return out


def _attr(name, attr):
    if attr is None:
        return '-1'
    if name == 'G_ICMP':
        return _PRED[attr]
    return str(int(attr))


def _node(rule, name, attr, ws, args, cls):
    info = ops.REGISTRY[name]
    ops3 = [_ref(a, rule) for a in args] + ['Ref()'] * (3 - len(args))
    defc = [str(cls.index(w)) for w in ws] + ['0'] * (2 - len(ws))
    opc = [str(cls.index(_width(rule, a))) for a in args] + \
        ['0'] * (3 - len(args))
    return ('{TargetOpcode::%s, %s, %d, %d, %s, {{%s}}, {{%s}}, {{%s}}}' %
            (name, _attr(name, attr), len(ws), len(args),
             'true' if info.commutative else 'false', ', '.join(ops3),
             ', '.join(defc), ', '.join(opc)))


def _array(typ, name, items):
    if not items:
        return [], 'ArrayRef<%s>()' % typ
    lines = ['static const %s %s[] = {' % (typ, name)]
    lines += ['    %s,' % x for x in items]
    lines.append('};')
    return lines, name


def cpp_rule(rule):
    rid = rule['id']
    src = rule['source']
    plan = rule['plan']
    cls = _classes(rule)
    out = ['/// %s: %s' % (rid, rule['source_text']),
           '///   %s' % rule['candidate']['text'],
           '///   cost %d -> %d; defined(%s); widths %s' % (
               rule['candidate']['estimated_cost']['before'],
               rule['candidate']['estimated_cost']['after'],
               ', '.join('x%d' % i for i in plan['guards']['defined']),
               '; '.join(','.join('%d' % w for _, w in m)
                         for m in plan['guards']['width_maps']))]
    srcs = [_node(rule, i['op'], i.get('attr'), i['ws'],
                  [tuple(a) for a in i['args']], cls)
            for i in src['instrs']]
    steps = []
    for s in plan['match_order']:
        if s['how'] == 'anchor':
            steps.append('{%d, Find::Anchor, Ref()}' % s['node'])
        elif s['how'] == 'def':
            steps.append('{%d, Find::DefOf, src(%d, %d)}' % (
                s['node'], s['via'][0], s['via'][1]))
        else:
            steps.append('{%d, Find::UserOf, %s}' % (
                s['node'], _ref(tuple(s['via']), rule)))
    act = {'erase': 'Action::Erase', 'replace': 'Action::Replace',
           'keep': 'Action::Keep', 'relax': 'Action::Relax'}
    actions = [act[m['action']] for m in plan['matched_instructions']]
    tgts = [_node(rule, n['op'], n.get('attr'), n['ws'],
                  [tuple(a) for a in n['args']], cls)
            for n in plan['new_instruction_dag']]
    outs = ['{%d, %d, %s, %d}' % (r['output'][0], r['output'][1],
                                  _ref(tuple(r['value']), rule),
                                  cls.index(_width(rule, ('n',) +
                                                   tuple(r['output']))))
            for r in plan['output_replacements']]
    incls = [str(cls.index(i['w'])) for i in src['inputs']
             if 'const' not in i]
    index = _input_index(rule)
    maps = []
    for m in plan['guards']['width_maps']:
        d = dict(m)
        maps.append(', '.join(str(d[w]) for w in cls))
    names = {}
    for typ, suffix, items in (('NodeDesc', 'Src', srcs),
                               ('MatchStep', 'Steps', steps),
                               ('Action', 'Actions', actions),
                               ('NodeDesc', 'Tgt', tgts),
                               ('OutputDesc', 'Outputs', outs),
                               ('uint8_t', 'InputClass', incls),
                               ('uint16_t', 'WidthMaps', maps)):
        lines, ref = _array(typ, '%s_%s' % (rid, suffix), items)
        out += lines
        names[suffix] = ref
    defined = sum(1 << index[i] for i in plan['guards']['defined'])
    distinct = sum(1 << index[i] for i in plan['guards']['distinct'])
    out.append('static const RuleDesc %s_Rule = {' % rid)
    out.append('    "%s", %s, %s, %s, %s, %s, %d, %s, 0x%x, 0x%x, %d, %s, '
               '%s};' % (
                   rid, names['Src'], names['Steps'], names['Actions'],
                   names['Tgt'], names['Outputs'], len(index),
                   names['InputClass'], defined, distinct, len(cls),
                   names['WidthMaps'],
                   'true' if plan.get('original_only') else 'false'))
    out.append('inline bool match_%s(MachineInstr &Root, '
               'const MachineRegisterInfo &MRI, JointPlan &Plan, '
               'const MatchEnv &Env) {' % rid)
    out.append('  return match(%s_Rule, Root, MRI, Plan, Env);' % rid)
    out.append('}')
    out.append('inline void apply_%s(MachineIRBuilder &B, '
               'const JointPlan &Plan) {' % rid)
    out.append('  apply(%s_Rule, B, Plan);' % rid)
    out.append('}')
    return out


def td_rule(rule):
    rid = rule['id']
    src = rule['source']
    plan = rule['plan']
    a = src['instrs'][plan['anchor']]
    defs = ['$d%d' % i for i in range(len(a['ws']))]
    uses = ['$o%d' % i for i in range(len(a['args']))]
    if a['op'] == 'G_ICMP':
        uses = ['$pred'] + uses
    if a['op'] == 'G_SEXT_INREG':
        uses = uses + ['$imm']
    pat = '(%s %s):$root' % (a['op'], ', '.join(defs + uses))
    return [
        '// %s: %s' % (rid, rule['source_text']),
        '//   -> %s' % rule['candidate']['text'],
        'def %s : GICombineRule<' % rid,
        '  (defs root:$root, gisynth_joint_plan:$plan),',
        '  (match %s,' % pat,
        '         [{ return gisynth::joint::rules::match_%s(*${root}, MRI, '
        '${plan}, JointEnv); }]),' % rid,
        '  (apply [{ gisynth::joint::rules::apply_%s(B, ${plan}); }])>;' %
        rid,
        '']


def emit(rules):
    """(td text, inc text, info) of the emittable rules, in their order."""
    ok, skipped = [], {}
    for r in rules:
        why = why_not_emittable(r)
        if why:
            skipped[r['id']] = why
        else:
            ok.append(r)
    td = ['// ' + HEADER, '// %d joint region rules.' % len(ok), '']
    for r in ok:
        td += td_rule(r)
    td.append('def gi_synth_joint_combines : GICombineGroup<[')
    for i, r in enumerate(ok):
        td.append('  %s%s' % (r['id'], ',' if i + 1 < len(ok) else ''))
    td.append(']>;')
    inc = ['// ' + HEADER,
           '// Included by lib/SynthJointCombiner.cpp. The rules are '
           'described for',
           '// GISelEGraphSynth/GISynthJoint.h; see girs/joint.py.',
           '// clang-format off', '']
    if ok:
        inc += ['namespace llvm {', 'namespace gisynth {', 'namespace joint {',
                'namespace rules {', '']
        for r in ok:
            inc += cpp_rule(r)
            inc.append('')
        inc += ['} // end namespace rules', '} // end namespace joint',
                '} // end namespace gisynth', '} // end namespace llvm', '']
    inc.append('// clang-format on')
    return '\n'.join(td) + '\n', '\n'.join(inc) + '\n', {
        'rules': len(ok), 'skipped': skipped}
